package com.cefrium

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * 从合并后的 runtime R.txt 为 Chromium 运行时需要的包生成 R.java。
 * 输出目录声明为 @OutputDirectory，供 variant.sources.java 的
 * addGeneratedSourceDirectory 接线（AGP 9 生成源码的正确通道）。
 */
abstract class GenerateCefriumRTask extends DefaultTask {

    @Input
    abstract Property<String> getVariantName()

    @Input
    abstract Property<String> getPackageList()

    @OutputDirectory
    abstract DirectoryProperty getOutDir()

    @TaskAction
    void generate() {
        def buildDir = project.layout.buildDirectory.get().asFile
        def baseDir = new File(buildDir,
            "intermediates/runtime_symbol_list/${variantName.get()}")
        def rTxt = null
        if (baseDir.isDirectory()) {
            rTxt = project.fileTree(baseDir).matching { include '**/R.txt' }
                .files.find { it.length() > 0 }
        }
        if (rTxt == null) {
            throw new IllegalStateException(
                "Cefrium: runtime R.txt not found under ${baseDir}; " +
                "the resources processing task must run before this task")
        }

        // 解析 R.txt：'int <type> <name> <value>' 与 'int[] styleable <name> { ... }'
        def entries = new TreeMap()
        rTxt.eachLine { line ->
            def parts = line.trim().split(/\s+/, 4)
            if (parts.length >= 4 && (parts[0] == 'int' || parts[0] == 'int[]')) {
                def type = parts[1]
                def name = parts[2]
                def value = parts[3]
                if (!entries.containsKey(type)) entries[type] = []
                entries[type].add([name, value])
            }
        }

        def out = outDir.get().asFile
        def count = 0
        packageList.get().split(',').each { pkg ->
            def pkgDir = new File(out, pkg.replace('.', '/'))
            pkgDir.mkdirs()
            def sb = new StringBuilder()
            sb.append('/* AUTO-GENERATED by CefriumPlugin. DO NOT EDIT. */\n')
            sb.append("package ${pkg};\n\n")
            sb.append('public final class R {\n')
            entries.each { type, names ->
                sb.append("  public static final class ${type} {\n")
                names.each { entry ->
                    def n = entry[0]
                    def v = entry[1]
                    if (v.startsWith('{')) {
                        sb.append("    public static final int[] ${n} = ${v};\n")
                    } else {
                        sb.append("    public static final int ${n} = ${v};\n")
                    }
                }
                sb.append('  }\n')
            }
            sb.append('}\n')
            new File(pkgDir, 'R.java').text = sb.toString()
            count++
        }
        logger.lifecycle(
            "Cefrium: Generated R for ${count} packages from ${rTxt.absolutePath} " +
            "(${entries.collect { it.value.size() }.sum()} symbols)")
    }
}
